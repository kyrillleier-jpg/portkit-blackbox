"""portkit's parameter ids on the Blackbox (JB1+pk), the one place they are decided.

The firmware's parameter table has 500 slots (ids 0 .. 0x1f3); stock and JOEBOX fill most of the upper part. The build
grows it to TABLE_SLOTS (bb/joebox/patches/pk.py: the 11 places in the parameter module that hold the size), and
portkit's parameters live above 0x1f3, where neither stock nor JOEBOX 1 registers anything (checked at build time:
tests/test_jb.py runs the whole registration). Pad parameters are ignored by the engine's pad handlers above 0x19a
(re/blackbox.md), global ones are only read by our code.

Presets and settings.tml store values by XML NAME, not by id: ids may move between builds without touching saved data.
The XML names below are therefore the stable part and must never change.
Generates bb/joebox/src/pk_ids.h (build.py).
"""

TABLE_SLOTS = 600            # was 500 (0x1f4)
FIRST = 0x200

# name: (id, scope, xml)
PARAMS = {
    # pad
    "SHIFT":    (0x200, "pad", "pkshift"),
    "PLAYLEN":  (0x201, "pad", "pkplaylen"),
    "STRETCH":  (0x202, "pad", "pkstretch"),
    "SMODE":    (0x203, "pad", "pkstretchmode"),
    "LFADE":    (0x204, "pad", "pkloopfade"),
    "FX3SEND":  (0x205, "pad", "pkfx3send"),
    # global: distortion
    "D_TYPE":   (0x220, "global", "pkdtype"),
    "D_DRIVE":  (0x221, "global", "pkddrive"),
    "D_TONE":   (0x222, "global", "pkdtone"),
    "D_MIX":    (0x223, "global", "pkdmix"),
    "D_LEVEL":  (0x224, "global", "pkdlevel"),
    # global: FX3
    "R_TYPE":   (0x228, "global", "pkfx3type"),
    "R_DECAY":  (0x229, "global", "pkfx3decay"),
    "R_DAMP":   (0x22a, "global", "pkfx3damp"),
    "R_PREDLY": (0x22b, "global", "pkfx3predelay"),
    "R_SIZE":   (0x22c, "global", "pkfx3size"),
    "R_LEVEL":  (0x22d, "global", "pkfx3level"),
    # global: SSL compressor (a model in JOEBOX's Compressor list)
    "S_THRESH": (0x230, "global", "pksslthresh"),
    "S_RATIO":  (0x231, "global", "pksslratio"),
    "S_ATTACK": (0x232, "global", "pksslattack"),
    "S_REL":    (0x233, "global", "pksslrelease"),
    "S_GAIN":   (0x234, "global", "pksslgain"),
    "S_MIX":    (0x235, "global", "pksslmix"),
    # global: Out 3 mirrors the headphone mix (INFO on Tools > Headphone)
    "MIRROR":   (0x238, "global", "pkmirror"),
    "MIRRORVOL": (0x239, "global", "pkmirrorvol"),
}

assert all(FIRST <= v[0] < TABLE_SLOTS for v in PARAMS.values())
assert len({v[0] for v in PARAMS.values()}) == len(PARAMS), "duplicate id"
assert len({v[2] for v in PARAMS.values()}) == len(PARAMS), "duplicate xml name"


def header():
    out = ["/* generated by bb/joebox/ids.py: portkit's parameter ids (do not edit) */", "#ifndef PK_IDS_H",
           "#define PK_IDS_H", f"#define PK_TABLE_SLOTS {TABLE_SLOTS}"]
    out += [f"#define P_{k:<10} 0x{v[0]:03x}   /* {v[1]}, xml {v[2]} */" for k, v in PARAMS.items()]
    out += ["#endif", ""]
    return "\n".join(out)


def ident(name):
    return PARAMS[name][0]
